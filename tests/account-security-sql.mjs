import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
const player='00000000-0000-4000-8000-000000000001',admin='00000000-0000-4000-8000-000000000002';
try {
  await db.exec(`create role anon;create role authenticated;create role service_role;create role authenticator;
    create schema auth;
    create table auth.users(id uuid primary key);
    create table auth.sessions(id uuid,user_id uuid);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
    create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('test.jwt',true),''),'{}')::jsonb $$;
    create table public.user_profiles(user_id uuid primary key);
    create table public.admin_users(user_id uuid primary key);
    create table public.cashier_profiles(user_id uuid primary key);
    create table public.private_data(user_id uuid,content text);
    alter table public.private_data enable row level security;
    create policy own_data on public.private_data for all to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
    grant usage on schema auth to authenticated; grant select,insert on public.private_data to authenticated;
    insert into auth.users values('${player}'),('${admin}');insert into public.user_profiles values('${player}'),('${admin}');
    insert into public.admin_users values('${admin}');insert into auth.sessions values('${player}','${player}');
    insert into public.private_data values('${player}','dato protegido');`);
  await db.exec(await readFile(new URL('../supabase/migrations/105_player_account_blocks.sql',import.meta.url),'utf8'));
  await db.exec(`create table public.player_session_revocations(user_id uuid primary key,revoked_at timestamptz default now());
    create table public.access_security_events(scope text,subject_hash text,created_at timestamptz default now());
    create function public.has_admin_permission(p text) returns boolean language sql stable as $$ select auth.uid()='${admin}'::uuid $$;
    create publication supabase_realtime;`);
  await db.exec(await readFile(new URL('../supabase/migrations/106_security_request_efficiency.sql',import.meta.url),'utf8'));
  await db.query("select set_config('test.uid',$1,false),set_config('test.jwt',$2,false)",[player,JSON.stringify({iat:1})]);
  assert.equal((await db.query('select public.account_access_allowed() allowed')).rows[0].allowed,true);
  const apply=(user,blocked,reason='Revisión manual de cuenta')=>db.query('select public.set_player_account_block($1,$2,$3,$4)',[user,admin,blocked,reason]);
  await assert.rejects(apply(admin,true));await assert.rejects(apply(player,true,'x'));
  await apply(player,true);
  assert.equal((await db.query('select count(*)::int n from auth.sessions')).rows[0].n,0);
  assert.equal((await db.query('select public.account_access_allowed() allowed')).rows[0].allowed,false);
  await assert.rejects(db.exec('select public.account_request_guard()'),/ACCOUNT_BLOCKED/);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from public.player_session_signals')).rows.length,1,'suspended owner can receive only their logout timestamp');
  assert.equal((await db.query('select * from public.private_data')).rows.length,0);
  await assert.rejects(db.query('select public.set_player_account_block($1,$2,$3,$4)',[player,admin,false,'Intento sin permiso']));
  await db.exec('reset role');await apply(player,false);
  assert.equal((await db.query('select public.account_access_allowed() allowed')).rows[0].allowed,false,'old token must remain revoked');
  const future=Math.floor(Date.now()/1000)+10;
  await db.query("select set_config('test.jwt',$1,false)",[JSON.stringify({iat:future})]);
  assert.equal((await db.query('select public.account_access_allowed() allowed')).rows[0].allowed,true);
  await db.exec('set role authenticated');assert.equal((await db.query('select * from public.private_data')).rows.length,1);
  await db.exec('reset role');assert.equal((await db.query('select count(*)::int n from public.player_account_events')).rows[0].n,2);
  await db.query("select set_config('test.uid',$1,false)",[admin]);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from public.player_session_signals')).rows.length,0,'other users cannot read logout signals');
  assert.equal((await db.query("select public.authorize_staff_access('users') allowed")).rows[0].allowed,true);
  await db.exec('reset role');
  await db.query(`insert into public.player_session_revocations(user_id) values($1)`,[player]);
  assert.equal((await db.query('select count(*)::int n from public.player_session_signals')).rows[0].n,1,'forced logout reuses one signal row');
  console.log('SQL: cuenta bloqueada, sesiones revocadas, JWT anterior rechazado, RLS, protección del personal, permisos e historial correctos.');
} finally { await db.close(); }
