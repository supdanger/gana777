// PostgreSQL aislado; no usa credenciales ni conexiones de producción.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE).href);
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role;
create schema auth; create table auth.users(id uuid primary key);
create table public.admin_users(user_id uuid primary key);
insert into auth.users values('10000000-0000-4000-8000-000000000001');`);
await db.exec(readFileSync(new URL('../supabase/migrations/100_reusable_player_entry.sql', import.meta.url), 'utf8'));
const id = '10000000-0000-4000-8000-000000000001';
const hash = 'a'.repeat(64);
await db.query('insert into public.player_entry_links(user_id,token_hash,expires_at) values($1,$2,now()+interval \'24 hours\')', [id,hash]);
const claim = () => db.query('select public.claim_player_entry($1) as id', [hash]);
assert.equal((await claim()).rows[0].id, id);
await assert.rejects(claim, /entry_busy/);
await db.exec("update public.player_entry_links set last_attempt_at=now()-interval '16 seconds'");
assert.equal((await claim()).rows[0].id, id, 'el mismo enlace se puede reutilizar');
await db.exec('set role anon');
await assert.rejects(claim, /permission denied/);
await assert.rejects(() => db.query('select * from public.player_entry_links'), /permission denied/);
await db.exec("reset role; update public.player_entry_links set revoked_at=now()");
await assert.rejects(claim, /entry_expired/);
await db.exec("update public.player_entry_links set revoked_at=null,expires_at=now()-interval '1 second'");
await assert.rejects(claim, /entry_expired/);
await db.exec("update public.player_entry_links set expires_at=now()+interval '24 hours',last_attempt_at=null; insert into public.admin_users select id from auth.users");
await assert.rejects(claim, /entry_expired/);
await db.close();
console.log('OK: reutilización, límite de intentos, permisos, vencimiento, revocación y exclusión de personal.');
